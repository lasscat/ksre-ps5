"""Embed binary files as C arrays: embed.py OUT.c name=path [name=path ...]

Generates `const unsigned char ksre_asset_<name>[]` and
`const unsigned long ksre_asset_<name>_len`. Portable replacement for
.incbin/xxd so the same source builds for macOS, Linux and the PS5.
"""
import sys


def main():
    out = sys.argv[1]
    with open(out, "w") as f:
        f.write("/* generated by tools/embed.py; do not edit or commit */\n")
        for spec in sys.argv[2:]:
            name, path = spec.split("=", 1)
            with open(path, "rb") as g:
                data = g.read()
            f.write("const unsigned char ksre_asset_%s[] = {\n" % name)
            for i in range(0, len(data), 24):
                f.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
            f.write("0};\nconst unsigned long ksre_asset_%s_len = %d;\n" % (name, len(data)))


if __name__ == "__main__":
    main()
