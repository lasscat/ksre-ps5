# Populate build/sysroot with every C dependency Ren'Py needs on the PS5 (milestone 03c):
#   * FFmpeg: our own LGPL-only build (ports/ffmpeg/build.sh)
#   * zlib bzip2 xz libpng libjpeg-turbo libwebp freetype harfbuzz fribidi SDL2_image:
#     staged from the pinned pacbrew bundle (tools/fetch-pacbrew.sh swgl)
# then link-checks them all (ports/deps-link-check.c) and writes build/sysroot/VERSIONS.txt.
set -euo pipefail
# shellcheck source=../tools/lib/common.sh
. "$(dirname "$0")/../tools/lib/common.sh"

root=${KSRE_PS5_ROOT}
sysroot="${root}/build/sysroot"
rel=$(lock_get PACBREW_SWGL_RELEASE)
pb="${PS5_PACBREW_PREFIX:-${root}/external/toolchains/pacbrew-${rel}/user/homebrew}"
sdk=${PS5_PAYLOAD_SDK:?set PS5_PAYLOAD_SDK (source .local-config/env.sh)}

"${root}/ports/ffmpeg/build.sh"

mkdir -p "${sysroot}/lib" "${sysroot}/include" "${sysroot}/lib/pkgconfig"
for l in libz libbz2 liblzma libpng16 libpng libjpeg libwebp libwebpdemux libsharpyuv \
         libfreetype libharfbuzz libfribidi libSDL2_image; do
  [ -f "${pb}/lib/${l}.a" ] || { echo "pacbrew bundle lacks ${l}.a" >&2; exit 1; }
  cp -f "${pb}/lib/${l}.a" "${sysroot}/lib/"
done
for h in zlib.h zconf.h bzlib.h lzma.h lzma png.h pngconf.h pnglibconf.h libpng16 jconfig.h \
         jerror.h jmorecfg.h jpeglib.h webp freetype2 harfbuzz fribidi; do
  cp -Rf "${pb}/include/${h}" "${sysroot}/include/"
done
mkdir -p "${sysroot}/include/SDL2"
cp -f "${pb}/include/SDL2/SDL_image.h" "${sysroot}/include/SDL2/"
for p in zlib liblzma libpng libjpeg libwebp libwebpdemux freetype2 harfbuzz fribidi SDL2_image; do
  cp -f "${pb}/lib/pkgconfig/${p}.pc" "${sysroot}/lib/pkgconfig/"
done

echo "link check"
"${sdk}/bin/prospero-clang" -std=gnu11 -Wall -c "${root}/ports/deps-link-check.c" \
  -I"${sysroot}/include" -I"${sysroot}/include/freetype2" -I"${sysroot}/include/harfbuzz" \
  -I"${sysroot}/include/fribidi" -I"${pb}/include" -I"${pb}/include/SDL2" \
  -o "${root}/build/sysroot/deps-link-check.o"
"${sdk}/bin/prospero-clang++" "${sysroot}/deps-link-check.o" -o "${sysroot}/deps-link-check.elf" \
  -L"${sysroot}/lib" -L"${pb}/lib" \
  -lSDL2_image -lwebpdemux -lwebp -lsharpyuv -lpng16 -ljpeg -lavformat -lavcodec -lswscale \
  -lswresample -lavutil -lharfbuzz -lfreetype -lfribidi -lbz2 -llzma -lz \
  -lSDL2 -liconv -lsamplerate -lSceSystemService -lSceUserService -lScePad -lSceAudioOut \
  -lSceVideoOut -lSceKeyboard -lSceImeDialog -lpthread -lm

ver() { grep -m1 '^Version' "${sysroot}/lib/pkgconfig/$1.pc" | cut -d' ' -f2; }
{
  echo "# Ren'Py C dependencies in build/sysroot (generated by ports/build-all-deps.sh)"
  echo "ffmpeg      $(lock_get FFMPEG_VERSION)   LGPL-2.1+ (own build, native decoders only)"
  echo "zlib        $(ver zlib)   zlib            (pacbrew ${rel})"
  echo "bzip2       1.0.8   BSD-style       (pacbrew ${rel})"
  echo "xz/liblzma  $(ver liblzma)   public domain/0BSD (pacbrew ${rel})"
  echo "libpng      $(ver libpng)  libpng licence  (pacbrew ${rel})"
  echo "libjpeg     $(ver libjpeg)   IJG/BSD-3      (pacbrew ${rel}, libjpeg-turbo)"
  echo "libwebp     $(ver libwebp)   BSD-3          (pacbrew ${rel})"
  echo "freetype    $(grep -m1 '^pkgver=' "${root}/external/pacbrew-repo/freetype/PKGBUILD" | cut -d= -f2)  FTL/GPLv2 (pick FTL)  (pacbrew ${rel}, no harfbuzz)"
  echo "harfbuzz    $(ver harfbuzz)   MIT            (pacbrew ${rel})"
  echo "fribidi     $(ver fribidi)  LGPL-2.1+      (pacbrew ${rel})"
  echo "SDL2_image  $(ver SDL2_image)   zlib           (pacbrew ${rel}; png/jpg/webp, no avif)"
  echo "assimp      not built (stub; no KSRE use)   live2d  excluded (proprietary)"
} > "${sysroot}/VERSIONS.txt"
cat "${sysroot}/VERSIONS.txt"
